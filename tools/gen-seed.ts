// Generates supabase/seed.sql from samples/world.json (the one source for seed, tests and sample images).
// Run: npm run seed
// The demo password lives only in .env.local (git-ignored). It is created here if missing and never printed;
// seed.sql gets a bcrypt hash, so the plaintext never appears in SQL, tool calls or git.
import { existsSync, readFileSync, appendFileSync, writeFileSync } from 'node:fs'
import { randomBytes } from 'node:crypto'
import bcrypt from 'bcryptjs'
import world from '../samples/world.json' with { type: 'json' }

const ROOT = new URL('..', import.meta.url).pathname
const ENV = ROOT + '.env.local'

function demoPassword(): string {
  const text = existsSync(ENV) ? readFileSync(ENV, 'utf8') : ''
  const found = text.match(/^DEMO_PASSWORD=(.+)$/m)?.[1]?.trim()
  if (found) return found
  const pw = 'demo-' + randomBytes(12).toString('base64url')
  appendFileSync(ENV, (text && !text.endsWith('\n') ? '\n' : '') + `DEMO_PASSWORD=${pw}\n`)
  console.log('Created DEMO_PASSWORD in .env.local (mock accounts only).')
  return pw
}

const q = (v: unknown) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const values = (rows: unknown[][]) => rows.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')

const parties = new Map(world.parties.map((p) => [p.key, p]))
const pos = new Map(world.purchase_orders.map((p) => [p.key, p]))
const hash = bcrypt.hashSync(demoPassword(), 10)

const sql = `-- GENERATED by tools/gen-seed.ts from samples/world.json. Do not edit by hand: change world.json and run \`npm run seed\`.
-- Mock data only: fake companies, GSTINs, bank numbers and .test emails.

insert into public.parties (id, type, name, gstin, bank_account, ifsc, phone, email, address, credit_limit, on_time_rate, avg_delay_days, outstanding, avg_invoice_amount) values
${values(world.parties.map((p) => [p.id, p.type, p.name, p.gstin, p.bank_account, (p as { ifsc?: string }).ifsc ?? null, p.phone, p.email, p.address, p.credit_limit, p.on_time_rate, p.avg_delay_days, p.outstanding, p.avg_invoice_amount]))}
on conflict (id) do update set name = excluded.name, gstin = excluded.gstin, bank_account = excluded.bank_account,
  phone = excluded.phone, email = excluded.email, address = excluded.address, credit_limit = excluded.credit_limit,
  on_time_rate = excluded.on_time_rate, avg_delay_days = excluded.avg_delay_days, outstanding = excluded.outstanding,
  avg_invoice_amount = excluded.avg_invoice_amount;

insert into public.purchase_orders (id, po_number, buyer_id, supplier_id, item, hsn, qty, unit_price, tax_rate, total, po_date) values
${values(world.purchase_orders.map((p) => [p.id, p.po_number, parties.get(p.buyer)!.id, parties.get(p.supplier)!.id, p.item, p.hsn, p.qty, p.unit_price, p.tax_rate, p.total, p.po_date]))}
on conflict (id) do nothing;

insert into public.delivery_receipts (id, po_id, grn_number, qty_delivered, delivered_on, confirmed_by_buyer) values
${values(world.delivery_receipts.map((r) => [r.id, pos.get(r.po)!.id, r.grn_number, r.qty_delivered, r.delivered_on, r.confirmed_by_buyer]))}
on conflict (id) do nothing;

-- Demo users. Token columns must be '' (not null) or GoTrue fails to sign them in.
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current,
  phone_change, phone_change_token, reauthentication_token) values
${world.users.map((u) => `  ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)}, ${q(hash)}, now(),
   '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: u.full_name }))}, now(), now(), '', '', '', '', '', '', '', '')`).join(',\n')}
on conflict (id) do update set encrypted_password = excluded.encrypted_password;

insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at) values
${world.users.map((u) => `  (${q(u.id)}, ${q(u.id)}, ${q(u.id)}, 'email', ${q(JSON.stringify({ sub: u.id, email: u.email, email_verified: true }))}, now(), now(), now())`).join(',\n')}
on conflict do nothing;

insert into public.profiles (id, role, party_id, full_name) values
${values(world.users.map((u) => [u.id, u.role, u.party ? parties.get(u.party)!.id : null, u.full_name]))}
on conflict (id) do update set role = excluded.role, party_id = excluded.party_id, full_name = excluded.full_name;
`

writeFileSync(ROOT + 'supabase/seed.sql', sql)
console.log(`Wrote supabase/seed.sql: ${world.parties.length} parties, ${world.purchase_orders.length} POs, ${world.delivery_receipts.length} receipts, ${world.users.length} users.`)
